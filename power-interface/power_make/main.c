// This makes delay work
// Taken from some random file generated by C*beMX2 and modified
uint32_t stick = 0;
uint32_t stock = 0; // increment in synchronous handler
void SysTick_Handler(void)
{
	HAL_IncTick();
	HAL_CORTEX_SYSTICK_IRQHandler();
	stick++;
	if(((stick & 0xffff) + 1) & 0xffff)
	{
		push_interrupt(1, FI_STICK, &stock);
	}
}

void HardFault_Handler(void)
{
	HAL_GPIO_WritePin(HAL_GPIOA, HAL_GPIO_PIN_5, HAL_GPIO_PIN_SET);
	while(1);
}

int main(void)
{
	// This was done after mpu, but it seems to work before too;
	if(HAL_Init() != HAL_OK)
	{
		return -1;
	}
	// these are in the same file, init.c
	init_mpu();
	init_icache();
	// don't know where to put this, it's too smol for own function;
	HAL_CORTEX_NVIC_SetPriorityGrouping(HAL_CORTEX_NVIC_PRIORITY_GROUP_4);
	init_rcc();
	// after this is done we can use err, noerr, etc;
	init_gpio();
	// now blink is ready
	/*
	 * You can start your application code here
	 */

	can_init(1, HAL_GPIOB, HAL_GPIO_PIN_8, HAL_GPIO_PIN_9);
	noerr(2);
	spi_inm_init();
	noerr(2);
//
	spi_sdm_init();
//	sdcard_startup(); // this starts init, when interrupt loop starts init will continue

//	push_interrupt(1, FI_CAN_RECVD, NULL);
	interrupt_loop(); // main loop
	noerr(10);

	// blinky for testing if loop has ended
	char nprev = 1;
	while (1) {
		int b = HAL_GPIO_ReadPin (HAL_GPIOC, HAL_GPIO_PIN_13) == HAL_GPIO_PIN_RESET;
		if(b == HAL_GPIO_PIN_RESET && nprev)
		{
			//Turn LED ON
			HAL_GPIO_TogglePin(HAL_GPIOA, HAL_GPIO_PIN_5);
			nprev = 0;
			HAL_Delay(10);
		}
		else if(!(b == HAL_GPIO_PIN_RESET))
		{
			//Turn LED OFF
			nprev = 1;
			HAL_Delay(10);
		}

		HAL_Delay(1);
	}
} /* end main */

