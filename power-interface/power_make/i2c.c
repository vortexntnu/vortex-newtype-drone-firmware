#include "stm32c5xx_hal_i2c.h"

#include "main.h"

hal_i2c_handle_t i2chan;
hal_i2c_handle_t* pi2chan;
int init_i2c(void)
{
	pi2chan = &i2chan;
	parserr(HAL_I2C_Init(pi2chan, HAL_I2C1));

	hal_i2c_config_t i2ccon =
	{
		.timing = 0x20500C16, // what even is this?
				      // according to the reference manual, section 41.9.5, page 1679,
				      // 31:28 is PRESC, prescaler value,
				      // 27:24 is reserved,
				      // 23:20 is SCLDEL, "data setup time",
				      // 19:16 is SDADEL, "data hold time",
				      // 15:8 is SCLH, "SCL high period",
				      // 7:0 is SCLL, "SCL low period",
				      // and the value is autogenerated, probably by cubemx,
				      // but there apparently exists a helper in the source files somewhere
		.addressing_mode = HAL_I2C_ADDRESSING_7BIT,
		.own_address1 = 93 << 1U // apparently, this is the first address of something,
					 // a 7bit value in bit 7:1
	};
	HAL_I2C_SetConfig(pi2chan, &i2ccon);
	HAL_I2C_EnableAnalogFilter(pi2chan);

}
