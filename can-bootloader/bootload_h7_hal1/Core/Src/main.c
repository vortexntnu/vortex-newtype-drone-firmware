// can functions
int can_senddata(uint8_t* data, uint8_t size, uint16_t id)
{
	FDCAN_TxHeaderTypeDef head =
	{
		.Identifier = id,
		.IdType = FDCAN_STANDARD_ID,
		.TxFrameType = FDCAN_DATA_FRAME,
		.DataLength = size,
		.ErrorStateIndicator = FDCAN_ESI_ACTIVE, // or PASSIVE, what does this even mean?
		.BitRateSwitch = FDCAN_BRS_OFF,
		.FDFormat = FDCAN_CLASSIC_CAN,
		.TxEventFifoControl = FDCAN_NO_TX_EVENTS,
		.MessageMarker = 0,
	};
	HAL_FDCAN_AddMessageToTxFifoQ(&hfdcan1, &head, data);
	return 0;
}
int can_getdata(uint8_t* place, uint8_t* size, uint16_t* id)
{
	FDCAN_RxHeaderTypeDef head;
	HAL_FDCAN_GetRxMessage(&hfdcan1, 0, &head, place);
	*id = head.Identifier;
	*size = head.DataLength;
	return 0;
}

