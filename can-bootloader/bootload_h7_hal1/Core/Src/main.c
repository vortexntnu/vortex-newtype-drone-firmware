int err(int num)
{
	for(int i = 0; i < 2*num; ++i)
	{
		BSP_LED_Toggle(LED_RED);
		HAL_Delay(100);
	}
	HAL_Delay(500);
	return 0;
}

int noerr(int num)
{
	for(int i = 0; i < 2*num; ++i)
	{
		BSP_LED_Toggle(LED_GREEN);
		HAL_Delay(100);
	}
	HAL_Delay(500);
	return 0;
}

int parserr(HAL_StatusTypeDef stat)
{
	int i = 0;
	if(stat != HAL_OK)
	{
		switch(stat)
		{
			case HAL_ERROR: /* HAL operation completed with error   */
				++i;
			case HAL_BUSY: /* HAL concurrent process ongoing       */
				++i;
//			case HAL_INVALID_PARAM: /* HAL invalid parameter                */ // doesn't exist in HAL1
//				++i;
			case HAL_TIMEOUT: /* HAL operation exceeds user timeout   */
				++i;
			default:
				err(i);
		}
	}
	return 0;
}

